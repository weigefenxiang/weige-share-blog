test('mention button opens native suggestions; undo and redo are real history actions', () => {
  const historySource=stripTypeScriptTypes(read('editor-history.ts'),{mode:'strip'})
    .replace('export class EditorHistory','class EditorHistory')
  const Engine=vm.runInNewContext(historySource+'\nEditorHistory',{}, {timeout:500})
  const store=new Engine('alpha')
  assert.equal(store.canUndo(),false)
  store.record('alpha!',5)
  store.record('alpha!!',6)
  assert.equal(store.undo(7).text,'alpha!')
  assert.equal(store.undo(6).text,'alpha')
  assert.equal(store.canUndo(),false)
  assert.equal(store.canRedo(),true)
  assert.equal(store.redo(5).text,'alpha!')
  store.record('alpha-new',6)
  assert.equal(store.canRedo(),false)
  store.sync('new reply target')
  assert.equal(store.canUndo(),false)
  assert.match(toolbar,/command: 'mention'/)
  assert.match(toolbar,/command: 'undo'/)
  assert.match(toolbar,/command: 'redo'/)
  assert.match(editor,/onMention=\{\(\) => handle\.current\?\.mention\(\)\}/)
  assert.match(editor,/onUndo=\{\(\) => handle\.current\?\.undo\(\)\}/)
  assert.match(editor,/onRedo=\{\(\) => handle\.current\?\.redo\(\)\}/)
  assert.match(input,/setToken\(\{ start, query: "" \}\)/)
  assert.match(input,/key === "z" \|\| key === "y"/)
  assert.match(input,/recordText\(next, start\)/)
  assert.match(input,/recordText\(edit\.text, start\)/)
})
